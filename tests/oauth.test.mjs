import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync('src/token.js', 'utf8').replace(/^\uFEFF/, '').replace(/^import .*;\r?$/gm, '').replace('export async function', 'async function');
const config = { enabled: false, keycloak_url: 'https://example.test/realms/test', client_id: 'test', redirect_uri: 'http://localhost:3000/search' };
let calls = [];
let cookie = 'old-token';
const context = vm.createContext({ config, URLSearchParams, Cookies: {get: () => { calls.push('cookie'); return cookie; }, remove: () => {cookie = undefined;}, set: (_, token) => {cookie = token;}}, fetch: async (url, options) => { calls.push({url, options}); return {ok:true, json:async () => url.endsWith('introspect') ? {active:true} : {access_token:'new-token'}}; }, window: {location:{hash:'', search:'', pathname:'/search'}, history:{replaceState(){}}}, document: {title:'test'} });
vm.runInContext(source, context);
assert.equal(await context.getAccessToken(), undefined);
assert.equal(calls.length, 0, 'Disabled auth must not read stale cookies or make requests');
config.enabled = true;
assert.equal(await context.getAccessToken(), 'old-token');
assert.equal(calls[1].url, 'https://example.test/realms/test/protocol/openid-connect/token/introspect');
cookie = undefined;
await context.getAccessToken();
assert.ok(context.window.location.href.startsWith('https://example.test/realms/test/protocol/openid-connect/auth?'));
context.window.location.hash = '#code=abc';
assert.equal(await context.getAccessToken(), 'new-token');
assert.equal(calls.at(-1).url, 'https://example.test/realms/test/protocol/openid-connect/token');
console.log('PASS: disabled auth, stale cookie bypass, introspection, redirect, code exchange');
